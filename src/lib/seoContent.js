const DEFAULT_COPY = {
  title: 'חיפוש מקומות להשכרה לפי שעה | PopSpot',
  intro: 'מצאו את המקום המדויק לפי שעה, יום או כמה שתצטרכו.',
};

/** Returns {title, intro} for a search page given its active category/city filters. */
export function getSearchLandingCopy({ category, city } = {}) {
  if (category && CATEGORY_COPY[category]) {
    return city ? CATEGORY_COPY[category].withCity(city) : CATEGORY_COPY[category].noCity();
  }
  if (city) return cityOnlyCopy(city);
  return DEFAULT_COPY;
}

